"""Synchronous domain ports; Qt clients use the queued gateway, never direct calls."""
from __future__ import annotations
from datetime import datetime
from typing import Protocol
from .models import (
    CommandResult, DecisionEnvelope, DisplayCommand, DisplayReceipt, ErrorCode,
    Observation, RawSignals, UserStateEstimate, ProposedPlan, SessionCommand, SessionResult, TaskCommand,
    TaskView, ToolCall, ToolResult, TraceEvent, WorkSession,
)


class Clock(Protocol):
    def wall_now(self) -> datetime: ...
    def monotonic_now(self) -> float: ...


class MetricsSink(Protocol):
    def record(self, event: TraceEvent) -> None: ...


class SamplingSource(Protocol):
    def sample(self) -> RawSignals: ...


class StateEstimator(Protocol):
    def estimate(self, signals: RawSignals) -> UserStateEstimate: ...


class ObservationSource(Protocol):
    def read(self) -> Observation: ...


class FastPolicy(Protocol):
    def decide(self, observation: Observation, task: TaskView) -> str: ...


class SlowPlanner(Protocol):
    def plan(self, observation: Observation, task: TaskView, envelope: DecisionEnvelope,
             results: tuple[ToolResult, ...] = ()) -> ProposedPlan: ...


class DeliveryPort(Protocol):
    def show(self, command: DisplayCommand) -> DisplayReceipt | None: ...
    def dismiss(self, task_id: str) -> None: ...


class TaskService(Protocol):
    def apply(self, command: TaskCommand) -> CommandResult: ...
    def get(self, task_id: str) -> TaskView | None: ...
    def list_tasks(self) -> list[TaskView]: ...
    def observe(self, observation: Observation) -> None: ...
    def validate(self, envelope: DecisionEnvelope) -> ErrorCode | None: ...
    def accept_decision(self, plan: ProposedPlan) -> ErrorCode | None: ...
    def schedule_recheck(self, envelope: DecisionEnvelope, run_at: datetime) -> ErrorCode | None: ...
    def request_delivery(self, envelope: DecisionEnvelope) -> ToolResult: ...
    def record_receipt(self, receipt: DisplayReceipt) -> ErrorCode | None: ...
    def pump(self) -> None: ...


class WorkSessionService(Protocol):
    def apply(self, command: SessionCommand) -> SessionResult: ...
    def get(self, session_id: str) -> WorkSession | None: ...
    def list_sessions(self) -> list[WorkSession]: ...
    def pump(self) -> None: ...


class ToolExecutor(Protocol):
    def execute(self, call: ToolCall) -> ToolResult: ...
